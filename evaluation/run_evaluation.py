import json
import shutil
import sys
from datetime import datetime, timezone
from pathlib import Path
from urllib.parse import quote

ROOT=Path(__file__).resolve().parents[1] / "backend"
sys.path.insert(0,str(ROOT))
from src.asset_paths import IMAGE_ROOT, resolve_catalog_path
from calculate_metrics import read_csv, write_csv, calculate


def image_path(value):
    path=Path(value)
    if not path.is_absolute(): path=resolve_catalog_path(path)
    path=path.resolve()
    path.relative_to(IMAGE_ROOT)
    if not path.is_file(): raise ValueError('Dataset image unavailable')
    return path


def relative_image(value, output):
    import os
    return quote(os.path.relpath(image_path(value),output),safe='/')


