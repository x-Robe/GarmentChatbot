def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--run-live',action='store_true')
    parser.add_argument('--output',type=Path,default=Path(__file__).resolve().parent)
    args=parser.parse_args()
    if not args.run_live: parser.error('Pass --run-live for real LLM/Qdrant calls (may incur cost).')
    output=args.output.resolve();output.mkdir(parents=True,exist_ok=True)
    if any((output/name).exists() for name in ('results.csv','annotations.csv','run_manifest.json')):
        parser.error('Outputs already exist. Choose a fresh --output directory; labels are never overwritten.')
    source=Path(__file__).resolve().parent/'queries.csv'
    if output/'queries.csv'!=source:shutil.copyfile(source,output/'queries.csv')
    queries=read_csv(output/'queries.csv')
    from PIL import Image
    from chatbot import GarmentAgent
    from src.product_search import ProductSearch
    from src.zero_shot_classifier import ZeroShotTshirtClassifier
    from src.hybrid_image_search import retrieve_hybrid
    search=ProductSearch();agent=GarmentAgent(product_search=search)
    classifier=ZeroShotTshirtClassifier(search.embedder.embed_texts)
    # Read payload ID/path mapping once, no vectors and no collection mutations.
    catalog=[];offset=None
    while True:
        points,offset=search.client.scroll(collection_name=search.collection_name,offset=offset,limit=256,
            with_payload=['product_id','image_url'],with_vectors=False)
        catalog.extend(points)
        if offset is None:break
    manifest={'started_at_utc':datetime.now(timezone.utc).isoformat(),'model':search.embedder.model_name,
        'collection':search.collection_name,'catalog_points':len(catalog),'top_k':5,
        'source_exclusion':'All point IDs belonging to the source product or identical source path; applied to retrieval AND v2 candidate counts.',
        'primary_queries':10,'planned_runs':13,'references':{},'runs':[]}
    results=[];runs=[];vectors={}
    result_fields=['query_id','search_type','user_query','reference_image','variant','product_id','point_id','rank','similarity_score','attributes','image_path','relevance']
    run_fields=['query_id','variant','status','returned_count','source_excluded','error_type']
    annotation_fields=['query_id','variant','rank','product_id','relevance','reviewer','notes']
    for query in queries:
        q=query['query_id'];variants=['v1','v2'] if query['search_type']=='image' else ['text' if query['search_type']=='text' else 'image_text']
        for variant in variants:
            run=dict(query_id=q,variant=variant,status='ok',returned_count=0,source_excluded='not_applicable',error_type='')
            trace={'query_id':q,'variant':variant}
            try:
                if variant=='text':
                    response=agent.respond(query['user_query'],mode=query['mode'])
                    products=response['products']
                    if response['intent']!='search' or response['effective_count']!=5:raise ValueError('Evaluation request did not resolve as top-five search')
                    trace.update(resolved_query=response['resolved_query'],strategy=response['search_strategy'])
                else:
                    name=query['reference_image']
                    if name not in vectors:
                        path=image_path(name)
                        matching=[p for p in catalog if Path((p.payload or {}).get('image_url','')).name==path.name]
                        if not matching:raise ValueError('Source product mapping unavailable')
                        source_ids={str(p.payload.get('product_id')) for p in matching if p.payload.get('product_id') is not None}
                        points=[str(p.id) for p in catalog if str((p.payload or {}).get('product_id')) in source_ids or p in matching]
                        with Image.open(path) as image:vector=search.embedder.embed_pil_image(image)
                        attrs=classifier.analyze(vector)
                        vectors[name]=(vector,attrs,points,source_ids)
                        manifest['references'][name]={'sha256':hashlib.sha256(path.read_bytes()).hexdigest(),
                            'embedding_sha256':hashlib.sha256(vector.tobytes()).hexdigest(),'dimension':int(vector.shape[0]),
                            'source_product_ids':sorted(source_ids),'excluded_point_ids':points,'analysis':attrs}
                    vector,attrs,points,source_ids=vectors[name]
                    excluded={'shown_point_ids':points}
                    filtered=lambda f:search._exclude_shown(f,excluded)
                    if variant=='v1':
                        raw=search._query_qdrant(vector,filtered(None),5)
                        products=search._format_results(raw,{})
                        trace.update(filters_used={},strategy='pure_visual')
                    else:
                        overrides={}
                        if variant=='image_text':
                            parsed=agent.attribute_extractor.extract_image_overrides(query['user_query'])
                            if parsed['intent']!='modify':raise ValueError('Modification was not resolved')
                            overrides=parsed['overrides'];trace['text_analysis']=parsed
                        raw,analysis,diagnostics=retrieve_hybrid(vector,attrs,5,
                            lambda f:search.client.count(collection_name=search.collection_name,count_filter=filtered(f),exact=True).count,
                            lambda v,f,n:search._query_qdrant(v,filtered(f),n),search._build_filter,mandatory=overrides)
                        products=search._format_results(raw[:5],analysis['filters_used'])
                        trace.update(image_analysis=analysis,diagnostics=diagnostics)
                    if any(str(p['product_id']) in source_ids or str(p['point_id']) in points for p in products):raise ValueError('Source exclusion failed')
                    run['source_excluded']='true'
                if len(products)>5 or len({str(p['product_id']) for p in products})!=len(products):raise ValueError('Invalid ranking')
                for rank,p in enumerate(products,1):
                    local=image_path(p['image_path']).relative_to(ROOT).as_posix()
                    results.append(dict(query_id=q,search_type=query['search_type'],user_query=query['user_query'],reference_image=query['reference_image'],variant=variant,
                        product_id=p['product_id'],point_id=p['point_id'],rank=rank,similarity_score=p.get('similarity_score',''),
                        attributes=json.dumps(p['attributes'],ensure_ascii=False,sort_keys=True),image_path=local,relevance=''))
                run['returned_count']=len(products)
            except Exception as error:
                # No raw exception strings: external clients may include credentials.
                results[:]=[r for r in results if (r['query_id'],r['variant'])!=(q,variant)]
                run.update(status='unavailable',returned_count=0,error_type=type(error).__name__)
            runs.append(run);manifest['runs'].append({**run,**trace})
            write_csv(output/'results.csv',result_fields,results)
            write_csv(output/'runs.csv',run_fields,runs)
            (output/'run_manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n')
            print(q,variant,run['status'],run['returned_count'],flush=True)
    annotations=[{**{k:r[k] for k in annotation_fields[:4]},'relevance':'','reviewer':'','notes':''} for r in results]
    write_csv(output/'annotations.csv',annotation_fields,annotations)
    manifest.update(completed_at_utc=datetime.now(timezone.utc).isoformat(),unique_returned_products=len({str(r['product_id']) for r in results}))
    (output/'run_manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n')
    gallery(output,queries,results,runs)
    calculate(output)
    if any(r['status']!='ok' for r in runs):raise RuntimeError('Some evaluation runs unavailable; see runs.csv')


if __name__=='__main__':
    try:main()
    except Exception as error:
        print(f'Evaluation stopped ({type(error).__name__}); inspect runs.csv or local configuration. No relevance labels generated.',file=sys.stderr)
        sys.exit(1)
