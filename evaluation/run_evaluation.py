"""Small, read-only real retrieval study. Requires existing .env and model cache.

No collection writes, production patches or human labels. Existing search code
is reused with an evaluation-only HasId exclusion in both image arms and counts.
Run from release root: python evaluation/run_evaluation.py --run-live --output evaluation/run_2
Use --output evaluation/run_2 to preserve prior outputs on repeat runs.
"""
import argparse
import hashlib
