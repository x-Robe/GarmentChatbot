            variant=run['variant'];section+=f'<h3>{esc(variant)} — {run["returned_count"]} returned ({esc(run["status"])})</h3><div class="grid">'
            for row in (r for r in results if r['query_id']==q and r['variant']==variant):
                attributes=' '.join(f'data-{k.replace("_","-")}="{esc(row[k])}"' for k in ('query_id','variant','rank','product_id'))
                section+=f'<figure class="result" {attributes}><img loading="lazy" src="{relative_image(row["image_path"],output)}" alt="{esc(q)} {esc(variant)} rank {row["rank"]} product {esc(row["product_id"])}"><figcaption>Rank {row["rank"]} · Product {esc(row["product_id"])}<br><label>Relevance <select aria-label="{esc(q)} {esc(variant)} rank {row["rank"]} relevance"><option value="">Pending</option><option value="1">1 — Relevant</option><option value="0">0 — Not relevant</option></select></label><label>Notes <input class="note" aria-label="{esc(q)} {esc(variant)} rank {row["rank"]} notes"></label></figcaption></figure>'
            section+='</div>'
